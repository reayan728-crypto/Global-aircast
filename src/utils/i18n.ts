/**
 * Universal translation resolver with multi-level regional script fallbacks,
 * localStorage cache support, and parameter template interpolation.
 */
export function getTranslation(
  lang: LanguageCode,
  key: string,
  dynamicDict?: Record<string, string>
): string {
  // 1. Check dynamic runtime dictionary (from Gemini API translation cache)
  if (dynamicDict && dynamicDict[key]) {
    return dynamicDict[key];
  }

  // 2. Check primary language dictionary
  const dict = TRANSLATIONS[lang];
  if (dict && dict[key]) {
    return dict[key];
  }

  // 3. Script-aware regional fallbacks for Indian and European languages
  const indianLangs: LanguageCode[] = ['mr', 'gu', 'kn', 'ml', 'pa', 'ur', 'or', 'as'];
  if (indianLangs.includes(lang)) {
    if (TRANSLATIONS[lang]?.[key]) return TRANSLATIONS[lang][key];
    if (TRANSLATIONS.hi?.[key]) return TRANSLATIONS.hi[key];
  }

  const romanceLangs: LanguageCode[] = ['pt', 'it', 'fr'];
  if (romanceLangs.includes(lang)) {
    if (TRANSLATIONS[lang]?.[key]) return TRANSLATIONS[lang][key];
    if (TRANSLATIONS.es?.[key]) return TRANSLATIONS.es[key];
  }

  const germanicLangs: LanguageCode[] = ['nl', 'sv', 'de'];
  if (germanicLangs.includes(lang)) {
    if (TRANSLATIONS[lang]?.[key]) return TRANSLATIONS[lang][key];
    if (TRANSLATIONS.de?.[key]) return TRANSLATIONS.de[key];
  }

  if (lang === 'fa' && TRANSLATIONS.ar?.[key]) return TRANSLATIONS.ar[key];
  if (lang === 'he' && TRANSLATIONS.ar?.[key]) return TRANSLATIONS.ar[key];
  if (lang === 'ja' && TRANSLATIONS.zh?.[key]) return TRANSLATIONS.zh[key];
  if (lang === 'ko' && TRANSLATIONS.zh?.[key]) return TRANSLATIONS.zh[key];

  // 4. Default to English
  if (TRANSLATIONS.en?.[key]) {
    return TRANSLATIONS.en[key];
  }

  // 5. Final fallback: never show raw camelCase key to the user
  if (process.env.NODE_ENV === 'development') {
    console.warn(`[i18n] Missing key "${key}" for language "${lang}"`);
  }
  return key
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, (s) => s.toUpperCase())
    .trim();
}

/**
 * Format string with template placeholders like {aqi}, {hour}, {city}
 */
export function formatTranslation(
  template: string,
  params?: Record<string, string | number>
): string {
  if (!params) return template;
  let result = template;
  for (const [k, v] of Object.entries(params)) {
    result = result.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return result;
}

/**
 * Developer Verification Test: Audit all 37 languages for translation completeness
 */
export function runTranslationAudit(): {
  totalLanguages: number;
  totalKeys: number;
  report: Record<string, { translated: number; missing: number; completenessPercent: number }>;
} {
  const enKeys = Object.keys(TRANSLATIONS.en);
  const report: Record<string, { translated: number; missing: number; completenessPercent: number }> = {};

  for (const lang of LANGUAGES) {
    let translated = 0;
    for (const key of enKeys) {
      const val = getTranslation(lang.code, key);
      if (val && val !== key) {
        translated++;
      }
    }
    const missing = enKeys.length - translated;
    const completenessPercent = Math.round((translated / enKeys.length) * 100);
    report[lang.code] = { translated, missing, completenessPercent };
  }

  return {
    totalLanguages: LANGUAGES.length,
    totalKeys: enKeys.length,
    report
  };
}
